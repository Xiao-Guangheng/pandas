# -*- coding: utf-8 -*-
# ============================================================
# 第4章：布尔筛选与查询 -- 选出你想要的数据
# ============================================================
# 上一章的 loc/iloc 是"点菜"（我知道要第几行第几列），
# 这一章是"提要求"（把所有满足条件的行给我）。
#
# 这套思路你在 NumPy 第 9 章已经学过（布尔掩码），Pandas 完全继承：
#   arr[arr > 5]          <- NumPy
#   df[df['分数'] > 5]    <- Pandas（条件换成"某一列"）
# 区别是 Pandas 的掩码带索引，而且可以组合多个条件、配合 loc 一起用。

import pandas as pd
import numpy as np

pd.set_option("display.unicode.east_asian_width", True)

# 本章示例：8 名学生的成绩表
df = pd.DataFrame({
    "姓名": ["张三", "李四", "王五", "赵六", "钱七", "孙八", "周九", "吴十"],
    "班级": ["一班", "一班", "一班", "一班", "二班", "二班", "二班", "二班"],
    "语文": [88, 92, 76, 59, 85, 90, 73, 66],
    "数学": [90, 85, 95, 78, 92, 88, 81, 70],
})
print("示例数据:")
print(df)


# ============================================================
# 4.1 单条件筛选
# ============================================================
print("=" * 50)
print("4.1 单条件筛选")

mask = df["语文"] > 80        # 布尔 Series（每行一个 True/False）
print("掩码长这样:")
print(mask)

print("\n语文 > 80 的行:")
print(df[mask])
print("\n惯用一行写法:")
print(df[df["语文"] > 80])

# 原理和 NumPy 一模一样：把布尔掩码当"筛子"，True 的行留下。
# df[布尔Series] 选行；df[列名] 选列——同一个 []，看传的是什么。


# ============================================================
# 4.2 多条件组合：& | ~ （不能写 and/or！）
# ============================================================
# 组合条件必须用位运算符 &（与）、|（或）、~（非），并且每个条件要加括号。
# 原因：Python 的 and/or 是"整体判断"，会先算成单个布尔值；
# 而 & 是"逐元素"运算，正是我们要的（和 NumPy 的规矩完全相同）。

print("\n" + "=" * 50)
print("4.2 多条件组合")

cond = (df["语文"] > 80) & (df["数学"] > 80)     # 两科都 > 80
print("两科都超过 80 的:")
print(df[cond])

cond2 = (df["班级"] == "二班") | (df["语文"] > 90)  # 二班 或 语文>90
print("\n二班的 或者 语文>90 的:")
print(df[cond2])

cond3 = ~(df["班级"] == "一班")                   # 不是一班（非）
print("\n不是一班的（~ 的用法）:")
print(df[cond3])

# 忘加括号会直接报错：(df["语文"] > 80) & df["数学"] > 80
# 因为运算符优先级问题。规矩：每个条件两边都加括号，别偷懒。


# ============================================================
# 4.3 配合 loc：筛选的同时只取需要的列
# ============================================================
# df[条件] 只能选行；df.loc[条件, 列] 可以"行按条件、列按名字"同时选，
# 而且还能直接对选中的格子赋值——这是数据分析最常用的骨架句式。

print("\n" + "=" * 50)
print("4.3 loc + 布尔掩码")

print("语文不及格（<60）的人的姓名:")
print(df.loc[df["语文"] < 60, "姓名"])

print("\n两科都 > 80 的人的姓名和数学:")
print(df.loc[(df["语文"] > 80) & (df["数学"] > 80), ["姓名", "数学"]])

# 修改：把数学不及格的同学数学改成 60（补考通过场景）：
df_fix = df.copy()
df_fix.loc[df_fix["数学"] < 60, "数学"] = 60
print("\n修改后（虽然没人不及格，语法记住就行）:")
print(df_fix[df_fix["数学"] == 60])

# 再演示一个真实一点的：给语文 90+ 的同学加 5 分：
df_bonus = df.copy()
df_bonus.loc[df_bonus["语文"] >= 90, "语文"] = df_bonus["语文"] + 5
print("\n语文 90+ 的加分后:")
print(df_bonus.head(3))


# ============================================================
# 4.4 isin：是否在集合里
# ============================================================
print("\n" + "=" * 50)
print("4.4 isin")

names = ["张三", "王五", "周九"]
print(df[df["姓名"].isin(names)])

# 反向：不在集合里（~ 取反）
print("\n不在名单里的:")
print(df[~df["姓名"].isin(names)])

# isin 也常用于"多值类别"筛选，等价于多个 == 用 | 连起来，
# 但当值很多时 isin 明显更简洁。


# ============================================================
# 4.5 between：区间筛选
# ============================================================
print("\n" + "=" * 50)
print("4.5 between")

print("语文在 70~85 之间（闭区间）:")
print(df[df["语文"].between(70, 85)][["姓名", "语文"]])

# 等价于 (df["语文"] >= 70) & (df["语文"] <= 85)，但更省事。


# ============================================================
# 4.6 where 与 mask：不删除，只替换
# ============================================================
# df[条件] 会把不满足的行【删掉】；where 则是【保留所有行】，
# 不满足条件的位置填成指定值（默认 NaN）。

print("\n" + "=" * 50)
print("4.6 where / mask")

s = df["语文"]
print("where：满足条件的保留，不满足的变 NaN:")
print(s.where(s > 80))

print("\nwhere 指定替换值:")
print(s.where(s > 80, other=0))    # 不及 80 的都变 0

# mask 是 where 的反面：满足条件的被替换。
print("\nmask：满足条件的变 NaN:")
print(s.mask(s > 80))
# where/mask 常用于"脱敏"、"封顶"场景，比如把超高分都压到 100。

# DataFrame 也支持（对整个 df 判断时建议只用数值列）：
df_num = df[["语文", "数学"]]
print("\n整表 where：不到 80 的显示，80 以上的遮掉:")
print(df_num.where(df_num < 80))


# ============================================================
# 4.7 query：用字符串写条件（像 SQL 的 WHERE）
# ============================================================
# query 把条件写成一个字符串，列名直接当变量用，可读性很好，
# 尤其条件多的时候比一堆 & 和括号清爽。

print("\n" + "=" * 50)
print("4.7 query")

print(df.query("语文 > 80 and 数学 > 80"))
# 等价于 df[(df['语文']>80) & (df['数学']>80)]

print("\nquery 里 or / not 也能用:")
print(df.query("班级 == '一班' or 语文 > 90"))

# 引号规则：字符串值用单引号包起来（外面已用双引号）。
# 变量传递用 @：想在条件里用外部变量，前面加 @
threshold = 85
print("\nquery 用外部变量 @threshold:")
print(df.query("数学 > @threshold")[["姓名", "数学"]])

# 提示：query 适合"读起来舒服"；要赋值修改还是得回到 loc。
# 两种都要会，看到别人代码里的 query 不能懵。


# ============================================================
# 4.8 筛选后的常见陷阱：index 没变 + 视图问题
# ============================================================
print("\n" + "=" * 50)
print("4.8 筛选结果的两个注意点")

result = df[df["语文"] > 80]
print("筛选后的行索引还是原来的:", result.index.tolist())
# 行索引保留了 0,1,4,5（被筛掉的行让索引"有洞"）。
# 想要 0,1,2,... 连续索引，用 reset_index：
print("reset_index(drop=True) 丢弃原索引:")
print(result.reset_index(drop=True).head(3))
# drop=True 表示"原索引不要了"；不加 drop 会把原索引变成一列。

# 第二个注意点：筛选得到的是【新 DataFrame】，直接给它赋值
# 不会影响原表（pandas 3.0 的写时复制机制保证这点）：
result2 = df[df["语文"] > 80]
result2.loc[result2.index, "语文"] = 0
print("\n改了 result2，原表不受影响:", df["语文"].tolist())
# 想改原表，请回到原表上写条件：df.loc[条件, 列] = 值（4.3 节的做法）。


# ============================================================
# 4.9 实战小练习（自己先想答案再看输出）
# ============================================================
print("\n" + "=" * 50)
print("4.9 综合练习")

# Q1：一班里数学最高的三个人是谁？
print("Q1 一班数学前三:")
print(df[df["班级"] == "一班"].nlargest(3, "数学")[["姓名", "数学"]])

# Q2：总分超过 170，或者语文数学任一科满分（>=95）的人
df["总分"] = df["语文"] + df["数学"]
print("\nQ2 总分>170 或 任一科>=95:")
print(df[(df["总分"] > 170) | (df["语文"] >= 95) | (df["数学"] >= 95)][["姓名", "总分"]])
df = df.drop(columns=["总分"])   # 删除练习列，恢复原表

# Q3：把语文低于 70 的同学的语文"隐藏"（变 NaN），其他人保留
print("\nQ3 where 练习:")
print(df["语文"].where(df["语文"] >= 70))


# ============================================================
# 本章小结
# ============================================================
# 1. df[布尔Series] 筛行；条件组合用 & | ~ 且每个条件加括号
# 2. df.loc[条件, 列] = 值 是"筛选+修改"的标准句式
# 3. isin（集合）、between（区间）是高频糖
# 4. where/mask 保留全部行、只替换值，适合脱敏和封顶
# 5. query("条件字符串") 可读性好，外部变量用 @ 引用
# 6. 筛选结果是新表，不影响原表；索引有"洞"时 reset_index(drop=True)
