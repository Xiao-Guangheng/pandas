# -*- coding: utf-8 -*-
# ============================================================
# 第10章：分组 groupby -- Pandas 的灵魂
# ============================================================
# "每个班的平均分是多少？""每个月的销售额是多少？"
# 这类"每个 XX 的 YY"问题，就是 groupby 的主场。
#
# groupby 的思想叫"拆分-应用-合并"（split-apply-combine）：
#   1. 拆分：按班级把 40 行拆成两堆（一班一堆、二班一堆）
#   2. 应用：对每一堆分别算平均分
#   3. 合并：把每堆的结果拼回一张小表
#
#         班级=一班 -> [88,92,76] \
#                                +--> 各算一个 mean -> {一班: 85.3, 二班: 87.6}
#         班级=二班 -> [85,78,90] /
#
# 你在 NumPy 里学不到这个（ndarray 没有"标签"），这是 Pandas 的招牌能力。
# 把本章学透，Pandas 就算出师了。

import pandas as pd
import numpy as np

pd.set_option("display.unicode.east_asian_width", True)

# 本章示例：两个班、三名老师、四次考试
df = pd.DataFrame({
    "姓名": ["张三", "李四", "王五", "赵六", "钱七", "孙八", "周九", "吴十"],
    "班级": ["一班", "一班", "一班", "一班", "二班", "二班", "二班", "二班"],
    "性别": ["男", "男", "女", "女", "男", "女", "男", "女"],
    "语文": [88, 92, 76, 59, 85, 90, 73, 66],
    "数学": [90, 85, 95, 78, 92, 88, 81, 70],
})
print("示例数据:")
print(df)


# ============================================================
# 10.1 最简单的分组聚合：一步到位
# ============================================================
print("=" * 50)
print("10.1 分组求平均")

result = df.groupby("班级")["语文"].mean()
print(result)
# 读法（从里到外）：
#   df.groupby("班级")        -> 按"班级"把表分组（得到 GroupBy 对象）
#   ["语文"]                  -> 每组里只取"语文"列
#   .mean()                   -> 每组分别求平均
# 结果的索引是班级名，值是各组的平均分（一个小 Series）。

# 常见变体：
print("\n每班人数:")
print(df.groupby("班级").size())            # size 数行数（含缺失）
print(df["班级"].value_counts())             # value_counts 也能数（按多少排序）

print("\n每班语文最高分:")
print(df.groupby("班级")["语文"].max())

print("\n每班两科平均:")
print(df.groupby("班级")[["语文", "数学"]].mean().round(1))
# 取一列用 ["语文"]（得 Series），取多列用 [["语文","数学"]]（得 DataFrame）


# ============================================================
# 10.2 agg：一个分组算多个统计量
# ============================================================
print("\n" + "=" * 50)
print("10.2 agg 多统计量")

print("每班语文的 平均/最高/最低:")
print(df.groupby("班级")["语文"].agg(["mean", "max", "min"]).round(1))

# 不同列用不同统计量（传字典）：
print("\n语文要平均、数学要最大:")
print(df.groupby("班级").agg({"语文": "mean", "数学": "max"}))

# 命名聚合（最清晰，结果列名自己起）：
print("\n命名聚合（列名自定义）:")
print(df.groupby("班级").agg(
    语文平均=("语文", "mean"),
    数学最高=("数学", "max"),
    人数=("姓名", "count"),
).round(1))
# 格式：新列名 = (原列名, 统计函数)。可读性最好，正式代码推荐。


# ============================================================
# 10.3 多列分组：更细的"每个 XX"
# ============================================================
print("\n" + "=" * 50)
print("10.3 多列分组")

print("每个 班级 x 性别 的数学平均:")
print(df.groupby(["班级", "性别"])["数学"].mean())
# 结果的索引变成两层（班级, 性别），这叫 MultiIndex（多级索引）。
# 嫌它别扭的话，as_index=False 让分组列保持普通列：
print("\nas_index=False（分组列回到列里）:")
print(df.groupby(["班级", "性别"], as_index=False)["数学"].mean())
# 或者事后 reset_index() 效果一样。新手推荐后者，表更"平"更好懂。


# ============================================================
# 10.4 遍历分组：看清 groupby 的真面目
# ============================================================
print("\n" + "=" * 50)
print("10.4 遍历分组")

# GroupBy 对象本质是"组名 -> 子表"的集合，可以直接 for 循环：
for name, sub in df.groupby("班级"):
    print(f"组名: {name}，人数: {len(sub)}，语文平均: {sub['语文'].mean():.1f}")
# 每轮拿到 组名 和 这一组对应的子 DataFrame。
# 理解了这个，"分组后做任意复杂的事"就有了底：
# 你甚至可以手动把每组结果收集起来（但能用内置就别手动循环）。


# ============================================================
# 10.5 transform：把组统计量"贴回"每一行
# ============================================================
# 需求：想知道"每个人比本班平均高多少分"。
# 聚合出来的是一个数，但要比就得贴回 8 行里 -- 这正是 transform 的活。

print("\n" + "=" * 50)
print("10.5 transform")

df["本班语文平均"] = df.groupby("班级")["语文"].transform("mean")
df["与平均差"] = df["语文"] - df["本班语文平均"]
print(df[["姓名", "班级", "语文", "本班语文平均", "与平均差"]].round(1))
# transform 输出和原表【一样长】，每组内的每行都填上该组的统计值。
# 这是"组内对比"的标准解法：先 transform 再相减。

# 更进阶：组内标准化 (x - 组均值) / 组标准差，一行搞定：
z = df.groupby("班级")["语文"].transform(lambda x: (x - x.mean()) / x.std())
print("\n组内标准化后的语文:")
print(z.round(2).tolist())
# transform 也能接自定义函数（对每个组调用一次）。

df = df.drop(columns=["本班语文平均", "与平均差"])   # 清理练习列


# ============================================================
# 10.6 filter：按"组"的条件筛掉整组
# ============================================================
print("\n" + "=" * 50)
print("10.6 filter")

# 需求：只保留"全班语文平均 > 80"的班级的【所有行】。
print(df.groupby("班级").filter(lambda g: g["语文"].mean() > 80))
# filter 对每个组算一个 True/False，True 的组整组保留。
# 注意和 df.filter（筛列名）完全不是一回事，这里是 GroupBy.filter。


# ============================================================
# 10.7 apply：组内执行任意操作
# ============================================================
print("\n" + "=" * 50)
print("10.7 apply")

# 需求：每个班取语文最高的 2 个人（"每组前 N"是经典问题）：
# 注意：新版本 groupby.apply 会把分组列"班级"从子表里拿掉，不再传给函数，
# 所以函数里看不到"班级"列，结果里也没有它（和旧教程不一样！）。
top2 = df.groupby("班级", group_keys=False).apply(
    lambda g: g.nlargest(2, "语文")
)
print(top2)
# apply 把每个子表交给你的函数，函数返回的东西拼起来。
# group_keys=False 避免结果多一层组的索引（新版本默认就是 False）。

# 想把"班级"列带回来，先 reset_index 再设回，或者用下面的 rank 技巧：
print("\n把班级列补回来的写法:")
top2_full = df.groupby("班级", group_keys=False).apply(
    lambda g: g.nlargest(2, "语文").assign(班级=g.name)
)
print(top2_full[["班级", "姓名", "语文"]])
# g.name 是当前组的组名（这里是班级名），assign 临时加回这一列。

# "每组前 N"也可以不用 apply（排序 + 计数技巧）：
rank_in_group = df.groupby("班级")["语文"].rank(ascending=False, method="first")
print("\n不打 apply 的组内前 2（rank 技巧）:")
print(df[rank_in_group <= 2][["班级", "姓名", "语文"]])
# 排序法在数据大时更快，apply 法更灵活（可以做更复杂的事），都要会。


# ============================================================
# 10.8 组内累计：cumsum 等也能分组用
# ============================================================
print("\n" + "=" * 50)
print("10.8 分组累计")

# 按日期累计的场景更多，这里用班级示意：每人语文在本班内的累计和
df["班内语文累计"] = df.groupby("班级")["语文"].cumsum()
print(df[["班级", "姓名", "语文", "班内语文累计"]])
# cumsum/rank/diff 等"保长度"的方法都可以挂在 groupby 后面用。
df = df.drop(columns=["班内语文累计"])


# ============================================================
# 10.9 get_dummies：把类别变成 0/1 列（机器学习常用）
# ============================================================
print("\n" + "=" * 50)
print("10.9 get_dummies")

print(pd.get_dummies(df[["性别"]]))
# 类别列变成多个 0/1 列。给后续算法用，属于"顺路一提"。
print("\n带前缀版:")
print(pd.get_dummies(df["班级"], prefix="班"))


# ============================================================
# 10.10 实战：完整的学生分析报告
# ============================================================
print("\n" + "=" * 50)
print("10.10 综合实战")

report = df.copy()
report["总分"] = report["语文"] + report["数学"]

# 1) 每班的整体情况（命名聚合）
summary = report.groupby("班级").agg(
    人数=("姓名", "count"),
    语文平均=("语文", "mean"),
    数学平均=("数学", "mean"),
    总分最高=("总分", "max"),
).round(1)
print(summary)

# 2) 每班总分前 2 名（分组列不在子表里，用 g.name 补回来）
best = (report.groupby("班级", group_keys=False)
              .apply(lambda g: g.nlargest(2, "总分").assign(班级=g.name)))
print("\n每班总分前二:")
print(best[["班级", "姓名", "总分"]])

# 3) 谁超过了本班平均总分？
report["本班平均总分"] = report.groupby("班级")["总分"].transform("mean")
stars = report[report["总分"] > report["本班平均总分"]]
print("\n超过本班平均的:")
print(stars[["姓名", "班级", "总分", "本班平均总分"]].round(1))

# 4) 班级 x 性别 交叉平均
cross = report.groupby(["班级", "性别"])[["语文", "数学"]].mean().round(1)
print("\n班级 x 性别:")
print(cross)


# ============================================================
# 本章小结
# ============================================================
# 1. groupby = 拆分-应用-合并；df.groupby("键")["值"].统计()
# 2. agg：多统计量 / 字典 / 命名聚合（推荐）
# 3. 多列分组得 MultiIndex，as_index=False 或 reset_index() 拉平
# 4. transform 组统计量贴回每行 -> "和本组平均比"类需求
# 5. filter 按组条件保留/筛掉整组；apply 组内做任意事（每组前N等）
# 6. cumsum/rank/diff 等也能分组用
#
# groupby 是 Pandas 的分水岭：前面都是"热身"，这里才是"实战"。
