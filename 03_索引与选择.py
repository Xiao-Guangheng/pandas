# -*- coding: utf-8 -*-
# ============================================================
# 第3章：索引与选择 -- loc / iloc（全教程最重要的一章）
# ============================================================
# 拿到数据后 90% 的时间都在"选数据"：选某行、某列、某些满足条件的行。
# Pandas 选数据有一堆写法，但核心只有两员大将：
#
#   df.loc[行, 列]   -- 按【标签】选（名字是什么）
#   df.iloc[行, 列]  -- 按【位置】选（第几个，从 0 数）
#
# 记忆口诀：loc = label（标签），iloc = integer location（整数位置）。
# 把这两个用熟，其他写法（[]、at、iat）都是它们的快捷方式。
#
# ⚠️ pandas 3.0 提醒：老教程里 s[0] 自动当位置的模糊行为已删除，
#    [] 传整数只认"整数标签"。想要位置，老老实实写 iloc。

import pandas as pd
import numpy as np

pd.set_option("display.unicode.east_asian_width", True)

# 本章的示例表：4 名学生，行索引是学号（不是 0,1,2 这种默认索引）
df = pd.DataFrame({
    "姓名": ["张三", "李四", "王五", "赵六"],
    "班级": ["一班", "一班", "二班", "二班"],
    "语文": [88, 92, 76, 85],
    "数学": [90, 85, 95, 78],
}, index=["s1", "s2", "s3", "s4"])

print("示例数据:")
print(df)


# ============================================================
# 3.1 先复习：[] 的两种基本用法
# ============================================================
# df["列名"] 取列（第 2 章学过）；df[a:b] 切片取行（容易混淆，后面少用）。

print("=" * 50)
print("3.1 [] 的基本用法")

print(df["姓名"])          # 列 -> Series（最常用）
print(df[["姓名", "语文"]])  # 多列 -> DataFrame

# 行切片（注意：这是"位置切片"，右端不开区间，和 Python 切片一致）：
print("\n行切片 df[1:3]:")
print(df[1:3])             # 第 1、2 行（不含 3）
# [] 的行为取决于你传的是"列名"还是"切片"：
#   传列名 -> 选列；传切片 -> 选行。规则不统一，所以官方推荐统一用 loc/iloc。
# 看到这你大概明白了为什么 loc/iloc 才是主角。


# ============================================================
# 3.2 loc：按标签选
# ============================================================
# df.loc[行标签, 列标签]，行和列都接受：单个、列表、切片。
# ⚠️ loc 的切片是【闭区间】！两端都包含。这和 Python 切片相反。

print("\n" + "=" * 50)
print("3.2 loc 按标签选")

print("一行 + 一列 -> 标量:")
print(df.loc["s2", "语文"])            # 92（李四的语文分）

print("\n一行 -> Series:")
print(df.loc["s2"])                    # 行标签 s2，所有列
print(df.loc["s2", :])                 # 同上，写全了

print("\n多行多列 -> DataFrame:")
print(df.loc[["s1", "s3"], ["姓名", "数学"]])

print("\nloc 切片（注意两端都包含！）:")
print(df.loc["s1":"s3", "姓名":"语文"])
# s1 到 s3 有 s1,s2,s3 三行；姓名到语文有 姓名,班级,语文 三列。
# loc 的切片含头也含尾，这是它最容易踩的坑，多打印几次加深印象。

print("\n所有行 + 某些列:")
print(df.loc[:, ["姓名", "语文"]])     # 冒号 = 全部


# ============================================================
# 3.3 iloc：按位置选
# ============================================================
# df.iloc[行位置, 列位置]，位置从 0 开始数，规则和 NumPy 的 arr[,] 完全一样。
# 切片是 Python 风格的【左闭右开】。

print("\n" + "=" * 50)
print("3.3 iloc 按位置选")

print("第 2 行第 3 列（从 0 数）:", df.iloc[1, 2])   # 92

print("\n第 2 行:")
print(df.iloc[1])
print(df.iloc[1, :])

print("\n前 2 行、前 2 列:")
print(df.iloc[:2, :2])                 # 右端不含，和 NumPy 一致

print("\n花式索引（NumPy 的老朋友）:")
print(df.iloc[[0, 2], [0, 3]])         # 第 0、2 行 × 第 0、3 列

print("\n负索引也支持:")
print(df.iloc[-1, 0])                  # 最后一行第 0 列 -> 赵六
# 你在 NumPy 第 3 章学的索引切片知识，iloc 全盘照搬，零新知识。


# ============================================================
# 3.4 对比实验：loc 与 iloc 的核心区别
# ============================================================
# 同一个"第 2 行"，两种写法的坐标完全不同，写个对照表：

print("\n" + "=" * 50)
print("3.4 loc vs iloc 对照")

# 行索引是 s1~s4，所以"第 2 行"的标签是 s2，位置是 1。
print(df.loc["s2", "语文"], " <- loc['s2','语文'] 按名字")
print(df.iloc[1, 2], "      <- iloc[1,2] 按位置")

# 常见翻车：行索引恰好是 0,1,2... 时，loc[1] 和 iloc[1] 结果一样，
# 让人以为两者没区别；一旦行索引变成字符串/日期，loc[1] 立刻报错。
# 习惯：看到方括号里是"名字"就用 loc，是"第几个"就用 iloc。


# ============================================================
# 3.5 at 与 iat：取/改单个值的最快写法
# ============================================================
# 只取一个格子时，at/iat 比 loc/iloc 略快且语义更清楚：
#   at[行标签, 列标签] / iat[行位置, 列位置]，只接受标量。

print("\n" + "=" * 50)
print("3.5 at / iat")

print(df.at["s2", "数学"])    # 85
print(df.iat[2, 2])           # 76
# 也能用来赋值（下一章大量使用）：
df.iat[0, 2] = 89             # 把 s1 的语文改成 89
print(df.at["s1", "语文"])    # 89
df.iat[0, 2] = 88             # 改回去


# ============================================================
# 3.6 用 loc/iloc 修改数据（赋值）
# ============================================================
# "取出来"和"改掉"是同一套语法，取完直接 = 赋值即可。
# 这是修改数据的【正确姿势】，配合下一章的条件筛选威力巨大。

print("\n" + "=" * 50)
print("3.6 用 loc 赋值")

df.loc["s2", "数学"] = 100              # 改一个格
print("李四数学改为 100:")
print(df.loc["s2"])

df.loc["s3", ["语文", "数学"]] = [80, 90  # 改一行多列
    ]
print("\n王五两科改为 80/90:")
print(df.loc["s3"])

df.loc[:, "总分"] = df["语文"] + df["数学"]   # 新建一整列（第 6 章细讲）
print("\n加一列总分:")
print(df)
df = df.drop(columns=["总分"])            # 删掉，恢复原样（drop 第 6 章细讲）


# ============================================================
# 3.7 重置与设置索引：set_index / reset_index
# ============================================================
# 行索引不是固定的，可以拿某一列来当，也可以还回去。

print("\n" + "=" * 50)
print("3.7 set_index / reset_index")

df2 = pd.DataFrame({
    "学号": ["s1", "s2", "s3", "s4"],
    "姓名": ["张三", "李四", "王五", "赵六"],
    "语文": [88, 92, 76, 85],
})

# 拿"学号"列当行索引（默认 drop=True 会把它从列里拿掉）：
df3 = df2.set_index("学号")
print("set_index 后:")
print(df3)
print("现在可以 df3.loc['s2', '姓名'] =", df3.loc["s2", "姓名"])

# reset_index：把行索引还原成一列，回到默认 0,1,2,...
print("\nreset_index 后:")
print(df3.reset_index())

# 行索引也可以直接赋值替换（不常用）：
df4 = df2.copy()
df4.index = ["a", "b", "c", "d"]
print("\n直接换行索引:")
print(df4)


# ============================================================
# 3.8 Series 的索引选择（和 DataFrame 同一套规则）
# ============================================================
print("\n" + "=" * 50)
print("3.8 Series 的 loc/iloc")

s = pd.Series([88, 92, 76, 85], index=["s1", "s2", "s3", "s4"])

print("s.loc['s2']      =", s.loc["s2"])       # 92
print("s.iloc[1]        =", s.iloc[1])          # 92
print("s.loc['s1':'s2'] 切片（闭区间）:")
print(s.loc["s1":"s2"])
print("s.iloc[0:2] 切片（左闭右开）:")
print(s.iloc[0:2])

# ⚠️ pandas 3.0 重点：老版本里 s[1] 会"猜"你的意思（标签？位置？），
# 现在 [] 只认标签。我们的行索引是字符串，所以 s[1] 会 KeyError。
# 自己取消注释试试：
# print(s[1])   # KeyError: 1
# 想按位置就用 s.iloc[1]，永远明确、永远不猜。


# ============================================================
# 3.9 布尔索引（下一章的主角，先打个照面）
# ============================================================
print("\n" + "=" * 50)
print("3.9 布尔索引预告")

# loc 的行参数还可以传"布尔 Series"（长度和行数相同）：
mask = df["语文"] > 85
print("语文 > 85 的行（用 loc[mask]）:")
print(df.loc[mask])
# 这就是 NumPy 布尔筛选的 Pandas 版，第 4 章整整一章都是它。


# ============================================================
# 本章小结
# ============================================================
# 1. loc 按标签、iloc 按位置；两者都是 df.loc[行, 列] 的形状
# 2. loc 切片是闭区间（含尾），iloc 切片是左闭右开（同 NumPy）
# 3. at/iat 是单个格子的快捷方式
# 4. 取和改同一套语法：df.loc[行, 列] = 值
# 5. set_index / reset_index 调整行索引
# 6. pandas 3.0：s[整数] 不再自动当位置用，统一写 iloc
#
# 练习建议：把示例 df 换成自己的数据，练到能脱口而出
# "这行代码会选出什么"再进入下一章。
