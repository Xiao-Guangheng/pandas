import numpy as np
import pandas as pd

# 索引与选择

#两个主要的选数据方法：loc 和 iloc
# 一个是按标签选择，一个是按照位置选择

pd.set_option("display.unicode.east_asian_width", True)
# 这是为了让输出的表格对齐，尤其是中文字符宽度问题。

df = pd.DataFrame({
    "姓名": ["张三", "李四", "王五", "赵六"],
    "班级": ["一班", "一班", "二班", "二班"],
    "语文": [88, 92, 76, 85],   
    "数学": [90, 85, 95, 78],
}, index=["s1", "s2", "s3", "s4"])

# 每一行是一个学生的成绩，行索引是学号（不是 0,1,2 这种默认索引）。
# 每一列是一个属性：姓名、班级、语文成绩、数学成绩。

# 之前的发方法取列，

pd["姓名"]  # 取列 -> Series
pd[["姓名", "语文"]]  # 多列 -> DataFrame

# 取行，切片取行（容易混淆，后面少用）。
pd[1:3]  # 第 1、2 行（不含 3）

# loc 按标签选

df.loc["s2", "语文"]  # 92（李四的语文分）
df.loc["s2"]  # 行标签 s2，所有列   
df.loc["s2", :]  # 同上，写全了
df.loc[["s1", "s3"], ["姓名", "数学"]]  #打印特定的行和列，这个打印的是张三和王五的姓名和数学成绩。
df.loc["s1":"s3", "语文":"数学"]  # 打印 s1 到 s3 的行，语文到数学的列，注意 loc 的切片是闭区间。
df.loc[:, ["姓名", "数学"]]  # 打印所有行的姓名和数学成绩

# 按位置选

df.loc["s2", "语文"]  # 92（李四的语文分）
df.iloc[1, 2]  # 92（李四的语文分）
# 表示第 1 行，第 2 列（注意：行列都是从 0 开始计数的）。
df.iloc[1]  # 行索引为 1 的行，所有列

# at 和 iat 取/改单个值的快捷写法

df.at["s2", "语文"]  # 92（李四的语文分）
df.iat[1, 2]  # 92（李四的语文分）
# 用于赋值
df.at["s2", "语文"] = 100  # 将李四的语文成绩改为 100
df.iat[1, 2] = 100  # 将李四的语文成绩改为 100

# 这两个主要用于单个值的赋值与改动

# 使用loc 和iloc赋值
df.loc["s2", "语文"] = 100  # 将李四的语文成绩改为 100
df.iloc[1, 2] = 100  # 将李四的语文成绩改为 100

df.loc["s2", ["语文", "数学"]] = [100, 90]  # 将李四的语文成绩改为 100，数学成绩改为 90
df.loc["s3", ["语文", "数学"]] = [80, 85]  # 将王五的语文成绩改为 80，数学成绩改为 85

# 重置与设置索引

df2 = pd.DataFrame({
    "学号": ["s1", "s2", "s3", "s4"],  # 这是一列
    "姓名": ["张三", "李四", "王五", "赵六"],  # 这是一列
    "语文": [88, 92, 76, 85], # 这是一列
})

df3=df2.set_index("学号")  # 将学号列设置为索引
df3.reset_index()  # 将索引重置为默认的整数索引，并将学号列恢复为普通列
# 之前没有设置的是默认的0,1,2,3
# 然后设置之后就是学号
# reset之后又是默认的了

# 行索引也可以直接用赋值替换，但是不常用

# series的索引选择和DataFrame是同一套规则
s = pd.Series([1, 2, 3, 4], index=["a", "b", "c", "d"])
s.loc["b"]  # 2
s.loc[["a", "c"]]  # 1,3
s.loc["a":"c"]  # 1,2,3

s.iloc[1]  # 2
s.iloc[[0, 2]]  # 1,3
s.iloc[0:3]  # 1,2,3

# 布尔索引

mask= df["语文"] > 80  # 语文成绩大于 80 的布尔掩码
df[mask]  # 取出语文成绩大于 80 的行